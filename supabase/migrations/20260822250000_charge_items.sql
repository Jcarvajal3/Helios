-- ============================================================================
-- Ronda — El cobro deja de ser un monto suelto y pasa a tener líneas
--
-- Hasta ahora `request_charge` recibía un número y ya: el cajero tecleaba
-- "$25" y nadie —ni el sistema, ni el cliente que escanea, ni el comercio
-- mañana— sabía de qué eran esos 25 dólares. El flujo nuevo del panel es un
-- carrito, así que el cobro tiene que llevar el detalle encima.
--
-- Por qué importa más allá de la pantalla:
--
--   * **El cliente ve qué está pagando antes de aceptar.** `preview_charge`
--     ya le decía el local y el monto; ahora le dice las líneas. Aceptar una
--     deuda a ciegas por un número es exactamente lo que no queremos de un
--     BNPL.
--   * **La línea es una foto, no un enlace.** Se guardan nombre y precio del
--     momento. Si mañana el local sube el ron a $25, el cobro de anoche sigue
--     diciendo $20 — un recibo que cambia solo no es un recibo.
--   * **El total lo calcula la base.** El panel manda producto y cantidad,
--     nunca el precio ni la suma. Un total viajando desde el navegador es un
--     total que se puede editar desde el navegador.
--
-- Se mantiene la línea de **monto libre**: hay locales sin catálogo, y
-- obligarlos a cargar productos para poder cobrar sería un paso atrás. La
-- diferencia es que ahora hasta ese caso deja escrito qué se cobró.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Número de orden legible por un humano
-- ---------------------------------------------------------------------------
-- El uuid del cobro sirve para el QR, no para hablar. Cuando el cajero tiene
-- que reclamar algo por teléfono, "la orden 1043" funciona y
-- "a3f2b8c1-…" no. Arranca en 1000: un "#1" en el primer cobro de un local
-- parece una prueba.

alter table public.charges
  add column order_number bigint generated by default as identity (start with 1000);

create unique index charges_order_number_idx on public.charges (order_number);

comment on column public.charges.order_number is
  'Número corto de la orden, para hablar de ella con un humano.';

-- ---------------------------------------------------------------------------
-- 2. Las líneas del cobro
-- ---------------------------------------------------------------------------

create table if not exists public.charge_items (
  id             uuid primary key default gen_random_uuid(),
  charge_id      uuid not null references public.charges (id) on delete cascade,
  -- Null en una línea de monto libre. También queda null si el producto se
  -- borra del catálogo después: por eso el nombre y el precio se copian aquí
  -- en vez de leerse del producto cada vez.
  product_id     uuid references public.products (id) on delete set null,
  name           text not null check (btrim(name) <> ''),
  unit_price_usd numeric(18,4) not null check (unit_price_usd >= 0),
  quantity       integer not null check (quantity > 0 and quantity <= 999),
  line_total_usd numeric(18,4)
    generated always as (round(unit_price_usd * quantity, 4)) stored,
  -- Orden en que las metió el cajero. Sin esto la lista sale en el orden que
  -- le apetezca a Postgres y el recibo no coincide con lo que se vio en la
  -- tablet.
  position       smallint not null default 0,
  created_at     timestamptz not null default now()
);

create index charge_items_charge_idx on public.charge_items (charge_id, position);

alter table public.charge_items enable row level security;

-- El personal del comercio ve las líneas de sus cobros, incluidos los
-- pendientes: la pantalla del QR enseña el resumen mientras espera al cliente.
create policy "charge_items_read_merchant_staff"
  on public.charge_items for select to authenticated
  using (
    charge_id in (
      select id from public.charges
      where merchant_id in (select public.my_merchant_ids())
    )
  );

-- El dueño del cobro ve qué compró. Mientras está pendiente el cobro no tiene
-- dueño, así que por aquí no se filtra nada: el cliente lo consulta con
-- `preview_charge`, que es security definer y comprueba lo suyo.
create policy "charge_items_read_own"
  on public.charge_items for select to authenticated
  using (
    charge_id in (
      select id from public.charges where user_id = (select auth.uid())
    )
  );

-- Sin políticas de escritura: las líneas solo las pone `request_charge`.
grant select on public.charge_items to authenticated;

-- ---------------------------------------------------------------------------
-- 3. request_charge con líneas
-- ---------------------------------------------------------------------------
-- Formato de `p_items` — un array, cada elemento una de estas dos formas:
--
--   {"product_id": "<uuid>", "quantity": 2}          ← del catálogo
--   {"name": "Consumo", "unit_price_usd": 12.5, "quantity": 1}  ← monto libre
--
-- En la primera, el precio y el nombre los pone la base leyendo `products`.
-- El navegador no los manda y por tanto no los puede tocar.

drop function if exists public.request_charge(uuid, uuid, numeric, text);

create or replace function public.request_charge(
  p_merchant_id     uuid,
  p_branch_id       uuid,
  p_items           jsonb,
  p_idempotency_key text
)
returns public.charges
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_staff   uuid := auth.uid();
  v_row     public.charges%rowtype;
  v_allowed boolean;
  v_item    jsonb;
  v_lines   jsonb := '[]'::jsonb;
  v_qty     integer;
  v_name    text;
  v_price   numeric(18,4);
  v_total   numeric(18,4);
begin
  if v_staff is null then
    raise exception 'No autenticado' using errcode = '28000';
  end if;

  select exists (
    select 1 from public.merchant_users
    where user_id = v_staff
      and merchant_id = p_merchant_id
      and is_active
      -- Un gerente (branch_id null) cubre todas las sucursales; un cajero
      -- solo la suya (ya lo exige el check cajero_requires_branch).
      and (branch_id is null or branch_id = p_branch_id)
  ) into v_allowed;

  if not v_allowed then
    raise exception 'No autorizado a cobrar en este comercio/sucursal' using errcode = '42501';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El cobro no tiene productos' using errcode = '22023';
  end if;

  if jsonb_array_length(p_items) > 100 then
    raise exception 'Demasiadas líneas en un mismo cobro' using errcode = '22023';
  end if;

  -- --- Resolver cada línea contra el catálogo ---------------------------
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := coalesce((v_item->>'quantity')::integer, 1);

    if v_qty < 1 or v_qty > 999 then
      raise exception 'Cantidad no válida: %', v_qty using errcode = '22023';
    end if;

    if nullif(v_item->>'product_id', '') is not null then
      select p.name, p.price_usd into v_name, v_price
      from public.products p
      where p.id = (v_item->>'product_id')::uuid
        and p.merchant_id = p_merchant_id
        and p.is_active;

      -- Pasa de verdad: el encargado de inventario quita un producto de la
      -- carta mientras el cajero lo tiene en el carrito.
      if not found then
        raise exception 'Un producto del pedido ya no está en tu carta; quítalo y vuelve a intentar'
          using errcode = '22023';
      end if;
    else
      v_name  := coalesce(nullif(btrim(v_item->>'name'), ''), 'Consumo');
      v_price := (v_item->>'unit_price_usd')::numeric;

      if v_price is null or v_price < 0 then
        raise exception 'Precio no válido en una línea del cobro' using errcode = '22023';
      end if;
    end if;

    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'product_id',     nullif(v_item->>'product_id', ''),
      'name',           v_name,
      'unit_price_usd', v_price,
      'quantity',       v_qty
    ));
  end loop;

  select sum(round((l->>'unit_price_usd')::numeric * (l->>'quantity')::integer, 4))
  into v_total
  from jsonb_array_elements(v_lines) l;

  -- El mínimo se comprueba sobre el total que acaba de calcular la base, no
  -- sobre uno que venga de fuera.
  if v_total < 5.00 then
    raise exception 'El monto mínimo por cobro es $5.00' using errcode = '22023';
  end if;

  -- Idempotente: si ya existe un cobro con esta clave (reintento de red del
  -- cajero), se devuelve el mismo en vez de generar un segundo QR vivo.
  insert into public.charges (merchant_id, branch_id, requested_by, amount_usd, idempotency_key)
  values (p_merchant_id, p_branch_id, v_staff, v_total, p_idempotency_key)
  on conflict (idempotency_key) do nothing
  returning * into v_row;

  if v_row.id is null then
    -- Ya existía: NO se vuelven a insertar las líneas, o el reintento
    -- duplicaría el detalle de un cobro que ya está en pantalla.
    select * into v_row from public.charges where idempotency_key = p_idempotency_key;
    return v_row;
  end if;

  insert into public.charge_items
    (charge_id, product_id, name, unit_price_usd, quantity, position)
  select
    v_row.id,
    (l->>'product_id')::uuid,
    l->>'name',
    (l->>'unit_price_usd')::numeric,
    (l->>'quantity')::integer,
    (ord - 1)::smallint
  from jsonb_array_elements(v_lines) with ordinality as t(l, ord);

  return v_row;
end;
$$;

revoke all on function public.request_charge(uuid, uuid, jsonb, text) from public, anon;
grant execute on function public.request_charge(uuid, uuid, jsonb, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 4. preview_charge enseña el detalle
-- ---------------------------------------------------------------------------
-- Igual que la versión de 20260822070000 más `items`, `order_number` y el
-- equivalente en bolívares. Lo que se añade es lo que el usuario necesita
-- para decidir: un BNPL en el que aceptas una deuda sin ver de qué es se
-- parece demasiado a firmar en blanco.

create or replace function public.preview_charge(p_charge_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
stable
as $$
declare
  v_user    uuid := auth.uid();
  v_charge  public.charges%rowtype;
  v_name    text;
  v_branch  text;
  v_avail   jsonb;
  v_items   jsonb;
  v_rate    numeric;
begin
  if v_user is null then
    raise exception 'No autenticado' using errcode = '28000';
  end if;

  select * into v_charge from public.charges where id = p_charge_id;
  if not found then
    raise exception 'Cobro no encontrado' using errcode = 'P0002';
  end if;

  select m.name, b.name into v_name, v_branch
  from public.merchants m
  join public.merchant_branches b on b.id = v_charge.branch_id
  where m.id = v_charge.merchant_id;

  select coalesce(jsonb_agg(
           jsonb_build_object(
             'name', ci.name,
             'quantity', ci.quantity,
             'unit_price_usd', ci.unit_price_usd,
             'line_total_usd', ci.line_total_usd
           ) order by ci.position
         ), '[]'::jsonb)
  into v_items
  from public.charge_items ci
  where ci.charge_id = v_charge.id;

  v_avail := public.my_available_balance();
  v_rate  := public.current_fx_rate();

  return jsonb_build_object(
    'charge_id', v_charge.id,
    'order_number', v_charge.order_number,
    'merchant_name', v_name,
    'branch_name', v_branch,
    'amount_usd', v_charge.amount_usd,
    -- El precio se pacta en dólares (docs/05 §1), pero quien paga piensa en
    -- bolívares. Se manda la tasa junto al monto para que la app pueda decir
    -- con qué número lo convirtió.
    'amount_ves', case when v_rate is null then null else round(v_charge.amount_usd * v_rate, 2) end,
    'fx_rate', v_rate,
    'items', v_items,
    'status', v_charge.status,
    'expired', v_charge.expires_at < now(),
    -- Ya reclamado por otra persona: la app debe decirlo con claridad en vez
    -- de dejar al usuario reintentando un QR muerto.
    'claimed_by_other', (v_charge.user_id is not null and v_charge.user_id <> v_user),
    'available_usd', (v_avail->>'available_usd')::numeric,
    'sufficient_balance', (v_avail->>'available_usd')::numeric >= v_charge.amount_usd
  );
end;
$$;

revoke all on function public.preview_charge(uuid) from public, anon;
grant execute on function public.preview_charge(uuid) to authenticated;
