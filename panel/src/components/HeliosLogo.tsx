type LogoProps = Omit<SVGProps<SVGSVGElement>, 'color'> & {
  /** Altura del logo en px o string CSS (por defecto 24). */
  height?: number | string
  /** Color de la palabra. Por defecto el del tema (`--color-logo-wordmark`). */
  color?: string
}

/** Los degradados del sol, con ids únicos: puede haber dos logos en la página. */
function Degradados({ prefijo }: { prefijo: string }) {
  return (
    <defs>
      {DEGRADADOS.map((g, i) => (
        <linearGradient
          key={i}
          id={`${prefijo}-${i}`}
          x1={g.x1}
          y1={g.y1}
          x2={g.x2}
          y2={g.y2}
          gradientUnits="userSpaceOnUse"
        >
          <stop stopColor={g.desde} />
          <stop offset="1" stopColor={g.hasta} />
        </linearGradient>
      ))}
    </defs>
  )
}

function Sol({ prefijo }: { prefijo: string }) {
  return (
    <>
      {RAYOS.map((r, i) => (
        <path key={i} d={r.d} fill={`url(#${prefijo}-${r.degradado})`} />
      ))}
    </>
  )
}

/**
 * El logotipo completo: el sol y la palabra. Para la cabecera del menú y el
 * login. Donde no cabe (la barra plegada, un favicon) va `HeliosIsotipo`.
 */
export function HeliosLogo({
  height = 24,
  color = 'var(--color-logo-wordmark)',
  style,
  ...props
}: LogoProps) {
  const prefijo = useId().replace(/:/g, '')
  return (
    <svg
      viewBox="166 104.5 858 275"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      style={{ height, width: 'auto', display: 'inline-block', ...style }}
      aria-label="Helios"
      role="img"
      {...props}
    >
      <Degradados prefijo={prefijo} />
      <Sol prefijo={prefijo} />
      {LETRAS.map((d, i) => (
        <path key={i} d={d} fill={color} />
      ))}
    </svg>
  )
}

/** Solo el sol, cuadrado. Para los sitios pequeños: la barra plegada, un avatar. */
export function HeliosIsotipo({
  size = 24,
  style,
  ...props
}: Omit<SVGProps<SVGSVGElement>, 'color'> & { size?: number | string }) {
  const prefijo = useId().replace(/:/g, '')
  return (
    <svg
      viewBox="166 104.5 275 275"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      style={{ height: size, width: size, display: 'inline-block', ...style }}
      aria-label="Helios"
      role="img"
      {...props}
    >
      <Degradados prefijo={prefijo} />
      <Sol prefijo={prefijo} />
    </svg>
  )
}
